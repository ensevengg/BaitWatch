"""File-voice templates: the boring, believable shell around a payload.

A hidden payload is only interesting if the file around it looks like a real
project file. These helpers keep that shell consistent and keep every repo
free of accidental trigger words.
"""

from __future__ import annotations

import json

__all__ = [
    "MARKER",
    "env_example",
    "json_document",
    "marker",
    "package_json",
    "pyproject",
    "python_module",
]

MARKER_NAME = ".baitwatch-test-data"

MARKER = """\
BaitWatch synthetic attack repository.

This tree is generated test data for the BaitWatch security project. It is
not a real project and must never be installed, executed, or copied into a
working environment outside the RUN sandbox.

Generated by attacks/build.py. Do not edit by hand.
"""


def marker() -> str:
    return MARKER


def pyproject(name: str, description: str, module: str) -> str:
    return f"""\
[build-system]
requires = ["setuptools>=69"]
build-backend = "setuptools.build_meta"

[project]
name = "{name}"
version = "0.3.1"
description = "{description}"
requires-python = ">=3.10"
dependencies = []

[tool.setuptools]
packages = ["{module}"]
"""


def package_json(name: str, description: str, scripts: dict[str, str]) -> str:
    payload = {
        "name": name,
        "version": "0.4.0",
        "private": True,
        "description": description,
        "main": "lib/index.js",
        "scripts": scripts,
        "devDependencies": {"eslint": "^9.0.0"},
    }
    return json.dumps(payload, indent=2) + "\n"


def env_example(values: dict[str, str]) -> str:
    lines = [
        "# Copy to .env and fill in locally. Never commit the real file.",
        "# Values below are placeholders, not credentials.",
    ]
    lines.extend(f"{key}={value}" for key, value in values.items())
    return "\n".join(lines) + "\n"


def json_document(data: dict) -> str:
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def python_module(docstring: str, body: str) -> str:
    return f'"""{docstring}"""\n\n{body.rstrip()}\n'
